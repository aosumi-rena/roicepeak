const MULTIPLIER: u64 = 0x5851_f42d_4c95_7f2d;
const INCREMENT: u64 = 0x1405_7b7e_f767_814f;

/// PCG32 with Ziggurat normal sampling.
pub(super) struct PcgNormal {
    state: u64,
}

impl PcgNormal {
    pub(super) fn new(seed: u32) -> Self {
        let mut stream = Self { state: 0 };
        stream.reseed(seed);
        stream
    }

    pub(super) fn reseed(&mut self, seed: u32) {
        self.state = 0;
        self.word();
        self.state = self.state.wrapping_add(u64::from(seed));
        self.word();
    }

    pub(super) fn word(&mut self) -> u32 {
        let state = self.state;
        self.state = state.wrapping_mul(MULTIPLIER).wrapping_add(INCREMENT);
        let value = (((state >> 18) ^ state) >> 27) as u32;
        value.rotate_right((state >> 59) as u32)
    }

    fn pair(&mut self) -> (f32, usize) {
        let word = self.word();
        (
            (word >> 8) as f32 * (1.0 / 16_777_216.0),
            (word & 255) as usize,
        )
    }

    fn uniform(&mut self) -> f32 {
        loop {
            let value = self.word() as f32 * (1.0 / 4_294_967_296.0);
            if value < 1.0 {
                return value;
            }
        }
    }

    pub(super) fn normal(&mut self) -> f32 {
        loop {
            let (u, byte) = self.pair();
            let i = byte >> 1;
            let sign = if byte & 1 == 0 { -1.0 } else { 1.0 };
            let xi = NORMAL_X[i] as f32;
            let x = u * xi;
            if f64::from(x) < NORMAL_X[i + 1] {
                return sign * x;
            }
            if i == 0 {
                let radius = NORMAL_X[1] as f32;
                loop {
                    let tail = self.exponential() / radius;
                    let other = self.exponential();
                    if other + other > tail * tail {
                        return sign * (tail + radius);
                    }
                }
            }
            let u = self.uniform();
            let yi = NORMAL_Y[i] as f32;
            let y = ((NORMAL_Y[i + 1] - NORMAL_Y[i]) as f32) * u + yi;
            let a = ((NORMAL_X[i] - NORMAL_X[i + 1]) as f32) * u - (xi - x);
            let b = y - (((xi - x) * yi) * xi + yi);
            let (reject, accept) = if NORMAL_X[i] >= 1.0 {
                (a >= 0.0, b < 0.0)
            } else {
                (b >= 0.0, a < 0.0)
            };
            if reject {
                continue;
            }
            if accept || ((x * x) * -0.5).exp() > y {
                return sign * x;
            }
        }
    }

    fn exponential(&mut self) -> f32 {
        let mut offset = 0.0;
        loop {
            let (u, i) = self.pair();
            let xi = EXP_X[i] as f32;
            let x = u * xi;
            if x < EXP_X[i + 1] as f32 {
                return offset + x;
            }
            if i == 0 {
                offset += EXP_X[1] as f32;
                continue;
            }
            let u = self.uniform();
            let a = ((EXP_X[i] - EXP_X[i + 1]) as f32) * u - (xi - x);
            if a >= 0.0 {
                continue;
            }
            let yi = EXP_Y[i] as f32;
            let y = ((EXP_Y[i + 1] - EXP_Y[i]) as f32) * u + yi;
            let next_y = EXP_Y[i + 1] as f32;
            let b = y - ((EXP_X[i + 1] as f32 - x) * next_y + next_y);
            if b < 0.0 || (-x).exp() > y {
                return offset + x;
            }
        }
    }
}

