//! Ordered shortcut slots and their default chords.
use super::{Chord, Command, Key, Modifiers};
use serde::{Deserialize, Serialize};

/// Named single-chord slots. Alternate slots remain independent of their command.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub enum Slot {
    FileNewProject,
    FileOpenFile,
    FileImportSrt,
    FileImportText,
    FileImportCsv,
    FileImportSsml,
    FileSaveProject,
    FileSaveProjectAs,
    Export,
    ExportBlock,
    ReplaceVoices,
    Preferences,
    KeySettings,
    CheckUpdate,
    About,
    Manual,
    Dictionary,
    Undo,
    Redo,
    Redo2,
    FindAndReplace,
    ShowSpeedPanel,
    ShowPitchPanel,
    ShowPausePanel,
    ShowGlobalEmotionPanel,
    PlayOrPause,
    PlayOrPause2,
    PlayCurrentBlock,
    ToggleLoopPlay,
    SkipToStart,
    SkipToEnd,
    MovePrevBlock,
    MovePrevBlock2,
    MoveNextBlock,
    MoveNextBlock2,
    TextEditorCopy,
    TextEditorPaste,
    TextEditorCut,
    TextEditorAllSelect,
    RegisterNewWord,
}
impl Slot {
    pub const MAIN_MENU: &'static [Self] = &[
        Self::FileNewProject,
        Self::FileOpenFile,
        Self::FileImportSrt,
        Self::FileImportText,
        Self::FileImportCsv,
        Self::FileImportSsml,
        Self::FileSaveProject,
        Self::FileSaveProjectAs,
        Self::Export,
        Self::ExportBlock,
        Self::ReplaceVoices,
        Self::Preferences,
        Self::KeySettings,
        Self::CheckUpdate,
        Self::About,
        Self::Manual,
        Self::Dictionary,
    ];
    pub const CONTROL: &'static [Self] = &[
        Self::Undo,
        Self::Redo,
        Self::Redo2,
        Self::FindAndReplace,
        Self::ShowSpeedPanel,
        Self::ShowPitchPanel,
        Self::ShowPausePanel,
        Self::ShowGlobalEmotionPanel,
        Self::PlayOrPause,
        Self::PlayOrPause2,
        Self::PlayCurrentBlock,
        Self::ToggleLoopPlay,
        Self::SkipToStart,
        Self::SkipToEnd,
        Self::MovePrevBlock,
        Self::MovePrevBlock2,
        Self::MoveNextBlock,
        Self::MoveNextBlock2,
    ];
    pub const TEXT_EDITOR: &'static [Self] = &[
        Self::TextEditorCopy,
        Self::TextEditorPaste,
        Self::TextEditorCut,
        Self::TextEditorAllSelect,
    ];
    pub fn all() -> impl Iterator<Item = Self> {
        Self::MAIN_MENU
            .iter()
            .chain(Self::CONTROL)
            .chain(Self::TEXT_EDITOR)
            .copied()
            .chain(std::iter::once(Self::RegisterNewWord))
    }
    pub fn command(self) -> Command {
        match self {
            Self::FileNewProject => Command::NewProject,
            Self::FileOpenFile => Command::OpenProject,
            Self::FileImportSrt => Command::ImportSrt,
            Self::FileImportText => Command::ImportText,
            Self::FileImportCsv => Command::ImportCsv,
            Self::FileImportSsml => Command::ImportSsml,
            Self::FileSaveProject => Command::SaveProject,
            Self::FileSaveProjectAs => Command::SaveProjectAs,
            Self::Export => Command::Export,
            Self::ExportBlock => Command::ExportBlock,
            Self::ReplaceVoices => Command::ReplaceVoices,
            Self::Preferences => Command::Preferences,
            Self::KeySettings => Command::KeyboardShortcuts,
            Self::CheckUpdate => Command::CheckForUpdates,
            Self::About => Command::About,
            Self::Manual => Command::Help,
            Self::Dictionary => Command::Dictionary,
            Self::Undo => Command::Undo,
            Self::Redo | Self::Redo2 => Command::Redo,
            Self::FindAndReplace => Command::FindReplace,
            Self::ShowSpeedPanel => Command::ShowSpeed,
            Self::ShowPitchPanel => Command::ShowPitch,
            Self::ShowPausePanel => Command::ShowPause,
            Self::ShowGlobalEmotionPanel => Command::ShowEmotion,
            Self::PlayOrPause | Self::PlayOrPause2 => Command::PlayPause,
            Self::PlayCurrentBlock => Command::PlayBlock,
            Self::ToggleLoopPlay => Command::ToggleLoop,
            Self::SkipToStart => Command::SkipStart,
            Self::SkipToEnd => Command::SkipEnd,
            Self::MovePrevBlock | Self::MovePrevBlock2 => Command::PreviousBlock,
            Self::MoveNextBlock | Self::MoveNextBlock2 => Command::NextBlock,
            Self::TextEditorCopy => Command::Copy,
            Self::TextEditorPaste => Command::Paste,
            Self::TextEditorCut => Command::Cut,
            Self::TextEditorAllSelect => Command::SelectAll,
            Self::RegisterNewWord => Command::RegisterWord,
        }
    }
    pub fn label(self) -> &'static str {
        match self {
            Self::FileNewProject => "New Project",
            Self::FileOpenFile => "Open File...",
            Self::FileImportSrt => "Import SRT file...",
            Self::FileImportText => "Import Text file...",
            Self::FileImportCsv => "Import CSV file...",
            Self::FileImportSsml => "Import SSML file...",
            Self::FileSaveProject => "Save Project",
            Self::FileSaveProjectAs => "Save As...",
            Self::Export => "Export",
            Self::ExportBlock => "Export Block",
            Self::ReplaceVoices => "Replace Voices",
            Self::Preferences => "Preferences...",
            Self::KeySettings => "Keyboard Shortcuts...",
            Self::CheckUpdate => "Check for updates...",
            Self::About => "About",
            Self::Manual => "Help Page",
            Self::Dictionary => "Dictionary",
            Self::Undo => "Undo",
            Self::Redo => "Redo",
            Self::Redo2 => "Redo 2",
            Self::FindAndReplace => "Find and Replace",
            Self::ShowSpeedPanel => "Show Speed Panel",
            Self::ShowPitchPanel => "Show Pitch Panel",
            Self::ShowPausePanel => "Show Pause Panel",
            Self::ShowGlobalEmotionPanel => "Show Emotion Panel",
            Self::PlayOrPause => "Play or Pause",
            Self::PlayOrPause2 => "Play or Pause 2",
            Self::PlayCurrentBlock => "Play Current Block",
            Self::ToggleLoopPlay => "Toggle loop playback",
            Self::SkipToStart => "Skip to start",
            Self::SkipToEnd => "Skip to end",
            Self::MovePrevBlock => "Move to Previous Block",
            Self::MovePrevBlock2 => "Move to Previous Block 2",
            Self::MoveNextBlock => "Move to Next Block",
            Self::MoveNextBlock2 => "Move to Next Block 2",
            Self::TextEditorCopy => "Copy",
            Self::TextEditorPaste => "Paste",
            Self::TextEditorCut => "Cut",
            Self::TextEditorAllSelect => "Select All",
            Self::RegisterNewWord => "Register a new word...",
        }
    }
    pub fn default_chord(self) -> Option<Chord> {
        use Key::*;
        let (key, modifiers) = match self {
            Self::FileNewProject => (Letter('N'), Modifiers::CONTROL),
            Self::FileOpenFile => (Letter('O'), Modifiers::CONTROL),
            Self::FileSaveProject => (Letter('S'), Modifiers::CONTROL),
            Self::FileSaveProjectAs => (Letter('S'), Modifiers::CONTROL_SHIFT),
            Self::Export => (Letter('M'), Modifiers::CONTROL),
            Self::ExportBlock => (Letter('M'), Modifiers::CONTROL_SHIFT),
            Self::ReplaceVoices => (Letter('R'), Modifiers::CONTROL),
            Self::CheckUpdate => (Function(5), Modifiers::NONE),
            Self::Manual => (Function(1), Modifiers::NONE),
            Self::Undo => (Letter('Z'), Modifiers::CONTROL),
            Self::Redo => (Letter('Y'), Modifiers::CONTROL),
            Self::Redo2 => (Letter('Z'), Modifiers::CONTROL_SHIFT),
            Self::FindAndReplace => (Letter('F'), Modifiers::CONTROL),
            Self::Dictionary => (Letter('D'), Modifiers::CONTROL),
            Self::PlayOrPause => (Space, Modifiers::NONE),
            Self::PlayOrPause2 => (Letter('P'), Modifiers::CONTROL),
            Self::PlayCurrentBlock => (Letter('B'), Modifiers::CONTROL),
            Self::ToggleLoopPlay => (Letter('L'), Modifiers::CONTROL),
            Self::SkipToStart => (Up, Modifiers::CONTROL),
            Self::SkipToEnd => (Down, Modifiers::CONTROL),
            Self::MovePrevBlock => (Up, Modifiers::NONE),
            Self::MoveNextBlock => (Down, Modifiers::NONE),
            Self::TextEditorCopy => (Letter('C'), Modifiers::CONTROL),
            Self::TextEditorPaste => (Letter('V'), Modifiers::CONTROL),
            Self::TextEditorCut => (Letter('X'), Modifiers::CONTROL),
            Self::TextEditorAllSelect => (Letter('A'), Modifiers::CONTROL),
            _ => return None,
        };
        Some(Chord::new(key, modifiers))
    }
}
